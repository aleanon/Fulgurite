//! Bake a TTF into `const` glyph data — `docs/plan-embedded.md` T13.7.
//!
//! `FontMetrics` is `fontdue`, which needs `alloc`, is a `std` crate,
//! and lives in `lumen-static-shell` — which M13 keeps `std`. So the
//! target has no measurer at all, and a `Label` there would lay out
//! glyphs nothing can draw. This writes the other half: advances and
//! coverage bitmaps in flash, measured and drawn with no allocation and
//! no shaping, which is what every embedded GUI does.
//!
//! Usage: `cargo run -p bake-font -- <font.ttf> <px> <out.rs>`
//!
//! Output goes in the *application*, not the core: the machinery
//! (`lumen_static::font::BakedFace`) is generic, the face is the app's,
//! and a GUI framework should not ship a font.

use std::fmt::Write as _;

/// Printable ASCII. A baked face is a fixed set of glyphs; anything
/// outside it measures as zero and draws nothing, which
/// `BakedFace::glyph` returning `Option` makes visible rather than
/// silently substituting a box.
const FIRST: char = ' ';
const LAST: char = '~';

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let [_, path, px, out] = &args[..] else {
        eprintln!("usage: bake-font <font.ttf> <px> <out.rs>");
        std::process::exit(2);
    };
    let px: f32 = px.parse().expect("px must be a number");

    let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("read {path}: {e}"));
    let font = fontdue::Font::from_bytes(bytes, fontdue::FontSettings::default())
        .unwrap_or_else(|e| panic!("parse {path}: {e}"));

    let lm = font.horizontal_line_metrics(px).expect("horizontal line metrics");

    // Coverage is one concatenated blob with per-glyph offsets rather
    // than a slice per glyph: that is how it lands in flash, and it
    // keeps the generated source to a readable size.
    let mut cov: Vec<u8> = Vec::new();
    let mut glyphs = String::new();
    let mut n = 0;
    for c in FIRST..=LAST {
        let (m, bitmap) = font.rasterize(c, px);
        let off = cov.len();
        cov.extend_from_slice(&bitmap);
        assert!(m.width <= u8::MAX as usize && m.height <= u8::MAX as usize, "glyph too large");
        writeln!(
            glyphs,
            "    Glyph {{ ch: {c:?}, advance: {:?}, w: {}, h: {}, left: {}, top: {}, off: {off} }},",
            m.advance_width,
            m.width,
            m.height,
            m.xmin,
            // fontdue reports ymin from the baseline upward; a painter
            // wants the top edge, which is what `top` means here.
            m.ymin + m.height as i32,
        )
        .unwrap();
        n += 1;
    }

    let mut s = String::new();
    writeln!(s, "//! Generated by `cargo run -p bake-font -- {path} {px} {out}`.").unwrap();
    writeln!(s, "//! Do not edit. Source face: {path} at {px} px, {n} glyphs, {} bytes of", cov.len()).unwrap();
    writeln!(s, "//! coverage. Regenerate rather than patching; `fixtures/embedded/tests/").unwrap();
    writeln!(s, "//! baked_face.rs` checks every byte against a live fontdue render.").unwrap();
    writeln!(s, "\nuse lumen_static::font::{{BakedFace, Glyph}};\n").unwrap();
    writeln!(s, "pub static FACE: BakedFace = BakedFace {{").unwrap();
    writeln!(s, "    px: {px:?},").unwrap();
    writeln!(s, "    line_height: {:?},", lm.new_line_size).unwrap();
    writeln!(s, "    ascent: {:?},", lm.ascent).unwrap();
    writeln!(s, "    glyphs: GLYPHS,").unwrap();
    writeln!(s, "    cov: COV,").unwrap();
    writeln!(s, "}};\n").unwrap();
    writeln!(s, "static GLYPHS: &[Glyph] = &[\n{glyphs}];\n").unwrap();
    writeln!(s, "static COV: &[u8] = &[").unwrap();
    for chunk in cov.chunks(32) {
        write!(s, "   ").unwrap();
        for b in chunk {
            write!(s, " {b},").unwrap();
        }
        s.push('\n');
    }
    writeln!(s, "];").unwrap();

    std::fs::write(out, s).unwrap_or_else(|e| panic!("write {out}: {e}"));
    println!("bake-font: {n} glyphs, {} bytes of coverage -> {out}", cov.len());
}
